#define AMOLED_FONT_GLYPH_COUNT (sizeof(amoledFont5x7) / sizeof(amoledFont5x7[0]))

static inline const uint8_t *amoledFontFind(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    for (unsigned i = 0; i < AMOLED_FONT_GLYPH_COUNT; i++)
    {
        if (amoledFont5x7[i].ch == c) return amoledFont5x7[i].rows;
    }
    return 0;
}

